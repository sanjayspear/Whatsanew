#!/usr/bin/env python3
"""
Generate the offline neighbourhood pack (Kotlin source) for a city from OpenStreetMap.

    curl -A "Pulse/0.2 (you@example.com)" https://overpass-api.de/api/interpreter --data-urlencode \
      'data=[out:json][timeout:120];node[place~"^(suburb|neighbourhood|quarter)$"](12.75,77.35,13.20,77.85);out tags center;' \
      -o places.json
    python tools/osm-pack/build_place_pack.py places.json --region IN-KA-BLR \
      --out apps/mobile/shared/core/src/commonMain/kotlin/dev/pulse/core/data/BengaluruPlaces.kt

Data (c) OpenStreetMap contributors, ODbL. Names that are ordinary words are skipped so they can't
be mistaken for places; well-known local short forms are added as aliases.
"""
import argparse
import json
import re

BLOCKED = {"market", "park", "lake", "garden", "temple", "church", "mosque", "station", "colony", "layout", "nagar",
           "extension", "block", "stage", "phase", "cross", "main", "road", "circle", "village", "town", "city", "new",
           "old", "east", "west", "north", "south", "central", "fashion", "food", "gym", "mall"}

# Local short forms people type, keyed by the OSM name (extend per city).
ALIASES = {
    "Rajarajeshwari Nagar": ["rr nagar", "r r nagar", "rajarajeshwarinagar"],
    "Banashankari": ["bsk"],
    "HSR Layout": ["hsr"],
    "BTM Layout": ["btm"],
    "Krishnarajapuram": ["kr puram", "k r puram"],
    "Jayanagar": ["jaynagar"],
    "Basavanagudi": ["basavangudi"],
    "Malleshwaram": ["malleswaram"],
    "Yeshwanthpur": ["yeshwantpur", "yesvantpur"],
    "Koramangala": ["kormangala", "koramangla"],
    "Indiranagar": ["indira nagar"],
    "Electronic City": ["e city", "ecity"],
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("places_json")
    ap.add_argument("--region", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--val", default="BengaluruOsmPlaces")
    a = ap.parse_args()
    seen = {}
    for e in json.load(open(a.places_json))["elements"]:
        t = e.get("tags", {})
        name = (t.get("name:en") or t.get("name") or "").strip()
        lat = e.get("lat") or e.get("center", {}).get("lat")
        lon = e.get("lon") or e.get("center", {}).get("lon")
        if not name or not name.isascii() or len(name) < 4 or lat is None:
            continue
        if name.lower() in BLOCKED or not re.search(r"[A-Za-z]{3}", name):
            continue
        seen.setdefault(name.lower(), (name, round(lat, 5), round(lon, 5)))
    lines = []
    for key in sorted(seen):
        name, lat, lon = seen[key]
        esc = name.replace("\\", "").replace('"', '\\"')
        aliases = ALIASES.get(name, [])
        extra = (", listOf(%s)" % ", ".join('"%s"' % x for x in aliases)) if aliases else ""
        lines.append('    Place("%s", %s, %s, "%s"%s),' % (esc, lat, lon, a.region, extra))
    src = (
        "package dev.pulse.core.data\n\n"
        "// GENERATED by tools/osm-pack/build_place_pack.py from OpenStreetMap (%d entries).\n"
        "// Data (c) OpenStreetMap contributors, available under the Open Database License (ODbL).\n"
        "// This is the offline \"place pack\" so area names resolve with zero network.\n\n"
        "internal val %s: List<Place> = listOf(\n%s\n)\n" % (len(lines), a.val, "\n".join(lines))
    )
    open(a.out, "w").write(src)
    print(f"{len(lines)} places -> {a.out}")


if __name__ == "__main__":
    main()
